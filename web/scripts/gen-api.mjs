// Generates src/api/schema.d.ts from the API contract (docs/api/openapi.json, kept by the server's contract test).
// Three corrections make the types say what the server actually sends:
// - The server reads numbers from strings too (ASP.NET's default), so the contract says "integer | string"; it always writes
//   numbers, so the types say number (number | null where the schema allows null).
// - It writes every property (none is ever left out, defaults included), so every property is required.
// - An enum used nullable anywhere gets null inside its shared schema; null is removed there, so a status is not nullable
//   everywhere because one field is.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const NUMBER = ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword);
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

/** The generated file's text, from the contract as it is on disk now. */
export async function generate() {
  const contract = JSON.parse(readFileSync(new URL("../../docs/api/openapi.json", import.meta.url), "utf8"));
  for (const schema of Object.values(contract.components?.schemas ?? {})) {
    if (Array.isArray(schema.enum)) schema.enum = schema.enum.filter((v) => v !== null);
    // A record parameter with a default (= null, = false) is left out of "required", but it is written all the same.
    if (schema.properties) schema.required = Object.keys(schema.properties);
  }
  const ast = await openapiTS(contract, {
    propertiesRequiredByDefault: true,
    transform(schema) {
      const type = schema.type;
      if (!Array.isArray(type) || !type.includes("string") || !(type.includes("integer") || type.includes("number"))) return undefined;
      return type.includes("null") ? ts.factory.createUnionTypeNode([NUMBER, NULL]) : NUMBER;
    },
  });
  return "// Generated by `npm run gen:api` from docs/api/openapi.json. Do not edit; change the API and regenerate.\n\n" + astToString(ast);
}

export const target = new URL("../src/api/schema.d.ts", import.meta.url);

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(target, await generate());
  console.log("src/api/schema.d.ts written from docs/api/openapi.json");
}
